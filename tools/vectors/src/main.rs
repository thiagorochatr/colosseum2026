//! Writes the withdraw circuit's test vectors as JSON on stdout.
//!
//! Every value comes from `mirror-core`, the same code the Solana program links,
//! so a circuit that accepts these vectors agrees with the on-chain Poseidon,
//! the zero ladder and the Merkle path convention. The circuit is never tested
//! against values it computed itself.

use mirror_core::{action_binding, commitment, nullifier, poseidon2, Field, MerkleTree, TREE_DEPTH};
use serde_json::{json, Value};

/// One SOL in lamports. The circuit treats the denomination as an opaque tag.
const DENOMINATION: u64 = 1_000_000_000;
const DEPOSITS: u64 = 6;
/// Deposits the curator leaves out of the clean set.
const EXCLUDED: [u64; 2] = [1, 4];

fn hex(f: &Field) -> String {
    format!("0x{}", f.to_bytes().iter().map(|b| format!("{b:02x}")).collect::<String>())
}

fn f(v: u64) -> Field {
    Field::from_u64(v)
}

struct Note {
    k: Field,
    r: Field,
}

fn note(i: u64) -> Note {
    Note {
        k: poseidon2(f(0xA11CE), f(i)).unwrap(),
        r: poseidon2(f(0xB0B), f(i)).unwrap(),
    }
}

fn leaf(n: &Note) -> Field {
    commitment(n.k, n.r, f(DENOMINATION)).unwrap()
}

/// A sample Solana action: pay `beneficiary` through relay `relay` for a fee.
fn sample_binding() -> Field {
    action_binding(0, &[0u8; 32], &[7u8; 32], &[9u8; 32], 5_000, 0, &[])
}

fn path_bits(index: u64) -> Vec<String> {
    (0..TREE_DEPTH).map(|j| ((index >> j) & 1).to_string()).collect()
}

fn siblings(tree: &MerkleTree, index: u64) -> Vec<String> {
    tree.proof(index).unwrap().siblings.iter().map(hex).collect()
}

/// A full circuit input: the note at `index`, proved against `pool` and `clean`.
fn input(n: &Note, index: u64, pool: &MerkleTree, clean: &MerkleTree, binding: Field) -> Value {
    json!({
        "poolRoot": hex(&pool.root().unwrap()),
        "cleanRoot": hex(&clean.root().unwrap()),
        "nullifierHash": hex(&nullifier(n.k).unwrap()),
        "binding": hex(&binding),
        "k": hex(&n.k),
        "r": hex(&n.r),
        "denomTag": hex(&f(DENOMINATION)),
        "pathIndices": path_bits(index),
        "poolSiblings": siblings(pool, index),
        "cleanSiblings": siblings(clean, index),
    })
}

fn main() {
    let notes: Vec<Note> = (0..DEPOSITS).map(note).collect();

    let mut pool = MerkleTree::new().unwrap();
    let mut clean = MerkleTree::new().unwrap();
    for (i, n) in notes.iter().enumerate() {
        pool.insert(leaf(n)).unwrap();
        let masked = if EXCLUDED.contains(&(i as u64)) { Field::ZERO } else { leaf(n) };
        clean.insert(masked).unwrap();
    }

    // A dishonest curator's clean tree: the honest mask plus a note that was
    // never deposited, at the next free index.
    let phantom = note(DEPOSITS);
    let mut padded_clean = clean.clone();
    padded_clean.insert(leaf(&phantom)).unwrap();

    let binding = sample_binding();
    let valid: Vec<Value> = (0..DEPOSITS)
        .filter(|i| !EXCLUDED.contains(i))
        .map(|i| {
            let mut v = input(&notes[i as usize], i, &pool, &clean, binding);
            v["_index"] = json!(i);
            v
        })
        .collect();
    let excluded: Vec<Value> = EXCLUDED
        .iter()
        .map(|&i| {
            let mut v = input(&notes[i as usize], i, &pool, &clean, binding);
            v["_index"] = json!(i);
            v
        })
        .collect();
    // The pool tree has no leaf at that index. An explicit zero leaf is the
    // empty leaf, so padding leaves the root unchanged and yields the path.
    let mut padded_pool = pool.clone();
    padded_pool.insert(Field::ZERO).unwrap();
    assert_eq!(padded_pool.root().unwrap(), pool.root().unwrap());
    let mut phantom_case = input(&phantom, DEPOSITS, &padded_pool, &padded_clean, binding);
    phantom_case["_index"] = json!(DEPOSITS);

    let out = json!({
        "_about": "Generated by tools/vectors from mirror-core. Do not edit by hand.",
        "depth": TREE_DEPTH,
        "denomination": DENOMINATION,
        "deposits": DEPOSITS,
        "excluded": EXCLUDED,
        "valid": valid,
        "rejected": {
            "excluded_note": excluded,
            "phantom_note_from_dishonest_curator": phantom_case,
        },
    });
    println!("{}", serde_json::to_string_pretty(&out).unwrap());
}
